/** The UI's one typeface: a hand-set 5×7 pixel font (plus a descender row),
 * after the old HD44780 character-LCD ROM — the most legible thing that fits
 * in five columns — and sixteen Elder-Futhark-ish runes the text flickers
 * through while it materializes.
 *
 * Glyphs are spelled as rows of `#` (ink) and `.` (air), top to bottom,
 * separated by spaces: 7 rows sit on the baseline, an optional 8th is the
 * descender (g, j, p, q, y, the comma). Most glyphs are 5 columns wide; the
 * few that must join their neighbours (em dash, ellipsis) use the 6th column,
 * which is otherwise the letter gap. Zero binary assets: this table IS the
 * font file. */

