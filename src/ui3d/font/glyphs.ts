/** A glyph as rows of booleans, GLYPH_H rows × GLYPH_W columns. */
export type Bitmap = boolean[][];

function parse(spec: string): Bitmap {
  const rows = spec.split(" ").filter((r) => r.length > 0);
  const out: Bitmap = [];
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] ?? "";
    const bits: boolean[] = [];
    for (let x = 0; x < GLYPH_W; x++) bits.push(row[x] === "#");
    out.push(bits);
  }
  return out;
}

/** Every drawable glyph in atlas order: font characters first, the runes
 * after them. `charIndex` maps a character to its slot. */
export const FONT_CHARS: string[] = Object.keys(GLYPHS);
const charIndex = new Map<string, number>(FONT_CHARS.map((c, i) => [c, i]));
/** Atlas slot of the replacement box for unknown characters. */
const MISSING = charIndex.get("□")!;
/** Atlas slot of the first rune. */
export const RUNE_BASE = FONT_CHARS.length;
/** Total glyph slots in the atlas. */
export const GLYPH_COUNT = FONT_CHARS.length + RUNES.length;

export function glyphBitmap(slot: number): Bitmap {
  if (slot >= RUNE_BASE) return parse(RUNES[slot - RUNE_BASE] ?? "");
  return parse(GLYPHS[FONT_CHARS[slot]!] ?? "");
}

/** Atlas slot for a character: exact glyph, alias, accent-stripped base
 * letter (a player named "Zoë" still renders), else the missing-glyph box. */
export function glyphSlot(char: string): number {
  const direct = charIndex.get(char);
  if (direct !== undefined) return direct;
  const alias = ALIASES[char];
  if (alias !== undefined) return charIndex.get(alias) ?? MISSING;
  const base = char.normalize("NFD").replace(/[̀-ͯ]/g, "");
  if (base.length === 1 && charIndex.has(base)) return charIndex.get(base)!;
  return MISSING;
}

/** Whether a slot draws no ink (spaces — skipped when building instances). */
export function isBlank(slot: number): boolean {
  return slot === charIndex.get(" ");
}
